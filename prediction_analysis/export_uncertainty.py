#!/usr/bin/env python3
"""Export an optional research artifact of empirical threshold-date MAE.

Evaluate J=3..10 on the existing cached experiment. No network requests are
made. Scores remain conditional on forecast and observed crossings within H.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from analyze import HORIZONS, calendar_alignment
from data import ROOT, json_file_sha256, message, write_json
from threshold_analysis import (
    cached_gts,
    cached_json,
    crossing_leads,
    existing_file,
    load_thresholds,
)


def export(cache: Path, output: Path, report: Path) -> dict:
    """Aggregate timing errors for every supported horizon, J and plant threshold."""
    manifest = cached_json(cache / "manifest.json")
    thresholds = np.array(sorted({row["threshold"] for row in load_thresholds()}))
    histories = np.arange(3, 11)
    shape = (3, 8, len(thresholds))
    total = np.zeros(shape)
    count = np.zeros(shape, dtype=np.int64)
    actual_count = np.zeros((3, len(thresholds)), dtype=np.int64)
    provenance = []
    for filename in manifest["files"]:
        path = existing_file(cache / filename)
        provenance.append(
            {
                "file": path.name,
                "sha256": json_file_sha256(path),
                "sha256_scope": "uncompressed_file",
            }
        )
        curves = cached_gts(path)
        for year in range(1980, 2027):
            curve = curves[year]
            previous = np.array(
                [
                    calendar_alignment(curves[year - j], year - j, year, len(curve))
                    for j in range(1, 11)
                ]
            )
            origins = len(curve) - 14
            predictions = np.full((origins, 28, 8), np.nan)
            for lead in range(1, 29):
                valid = min(origins, len(curve) - lead)
                increments = previous[:, lead : lead + valid] - previous[:, :valid]
                predictions[:valid, lead - 1] = (
                    curve[:valid, None]
                    + np.cumsum(increments, axis=0)[histories - 1].T / histories
                )
            actual, predicted, pending = crossing_leads(curve, predictions, thresholds)
            for hi, horizon in enumerate(HORIZONS):
                valid = len(curve) - horizon
                observed = actual[:valid]
                eligible = pending[:valid] & (observed <= horizon)
                actual_count[hi] += eligible.sum(axis=0)
                for ji in range(8):
                    matched = eligible & (predicted[:valid, :, ji] <= horizon)
                    errors = np.abs(predicted[:valid, :, ji].astype(int) - observed)
                    total[hi, ji] += np.where(matched, errors, 0).sum(axis=0)
                    count[hi, ji] += matched.sum(axis=0)
        message("INFO", f"Calibrated threshold dates from {filename}.")
    means = np.divide(total, count, out=np.zeros(shape), where=count > 0)
    data = {
        "description": "Conditional mean absolute GTS threshold crossing date error in days; not a confidence interval or observed flowering error.",
        "years": [1980, 2026],
        "archiveCutoff": manifest["end_date"],
        "locations": len(manifest["locations"]),
        "thresholds": thresholds.tolist(),
        "maeDays": {
            str(h): {
                str(j): [
                    round(float(value), 6) if n else None
                    for value, n in zip(means[hi, ji], count[hi, ji])
                ]
                for ji, j in enumerate(histories)
            }
            for hi, h in enumerate(HORIZONS)
        },
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "/** Empirical date errors generated by prediction_analysis/export_uncertainty.py. */\nexport const predictionCalibration = "
        + json.dumps(data, ensure_ascii=False, allow_nan=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    write_json(
        report,
        {
            "data": data,
            "matched_counts": count.tolist(),
            "actual_counts": actual_count.tolist(),
            "weather_files": provenance,
            "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "output_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        },
    )
    message("SUCCESS", f"Empirical threshold errors saved in {output}.")
    return data


def main() -> None:
    """Parse offline calibration paths and show useful reproduction examples."""
    parser = argparse.ArgumentParser(
        description=__doc__,
        add_help=False,
        epilog="Export empirical date errors from existing cached weather:\n  python prediction_analysis/export_uncertainty.py",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "-h", "--help", "-?", action="help", help="Show arguments and example."
    )
    parser.add_argument(
        "--cache",
        type=Path,
        default=ROOT / "cache",
        help="Weather cache directory (default: %(default)s).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "results/thresholds/predictionCalibration.js",
        help="Generated JavaScript module (default: %(default)s).",
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=ROOT / "results/thresholds/production_calibration.json",
        help="Calibration counts and provenance JSON (default: %(default)s).",
    )
    args = parser.parse_args()
    try:
        export(args.cache, args.output, args.report)
    except (OSError, ValueError, RuntimeError) as error:
        parser.exit(1, f"ERROR: {error}\n")


if __name__ == "__main__":
    main()
